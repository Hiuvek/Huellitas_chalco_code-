// Descarga la configuración pública del cliente; nunca la imprime ni la incorpora a Git.
import {spawnSync} from 'node:child_process';
import {readFileSync,writeFileSync,mkdirSync,existsSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=fileURLToPath(new URL('../../',import.meta.url));
const current=path.join(root,'app/google-services.json');
if(!existsSync(current)) throw new Error('Falta la configuración Android inicial.');
const data=JSON.parse(readFileSync(current,'utf8'));
if(data.project_info?.project_id!=='huellitas-chalco') throw new Error('Proyecto inesperado.');
const client=data.client?.find(c=>c.client_info?.android_client_info?.package_name==='com.example.huellitaschalco');
const appId=client?.client_info?.mobilesdk_app_id;
if(!appId) throw new Error('Falta la app Android del proyecto.');
const output=path.join(root,'build/cloud/google-services.download.json');
mkdirSync(path.dirname(output),{recursive:true});
const result=spawnSync(path.join(root,'tools/firebase/node_modules/.bin/firebase'),['apps:sdkconfig','ANDROID',appId,'--project','huellitas-chalco','--out',output],{cwd:root,stdio:'pipe',encoding:'utf8'});
if(result.status!==0) throw new Error('No se descargó la configuración. Revisa la sesión de Firebase CLI.');
const downloaded=JSON.parse(readFileSync(output,'utf8'));
if(downloaded.project_info?.project_id!=='huellitas-chalco'||!downloaded.client?.some(c=>c.client_info?.android_client_info?.package_name==='com.example.huellitaschalco')) throw new Error('La configuración descargada no coincide con el proyecto.');
writeFileSync(current,JSON.stringify(downloaded,null,2)+'\n');
console.log('Configuración Android actualizada. Spark usa Auth y Firestore; no se muestran claves.');
